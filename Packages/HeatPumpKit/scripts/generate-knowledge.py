#!/usr/bin/env python3
"""Compile Sources/<Target>/Knowledge/<lang>/*.md into Swift string constants.

Every target with a Knowledge folder (the core and each integration) gets its own
Sources/<Target>/KnowledgeContent.generated.swift; the markdown files stay the editable
source, one folder per language (en, nb), and every language must have the same documents.
Run this after editing them:
    python3 Packages/HeatPumpKit/scripts/generate-knowledge.py
A unit test fails when a generated file is out of date.
"""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
languages = ["en", "nb"]


def generate(target):
    source = target / "Knowledge"
    names = {lang: sorted(p.stem for p in (source / lang).glob("*.md")) for lang in languages}
    if len({tuple(n) for n in names.values()}) != 1:
        sys.exit(f"Knowledge documents in {target.name} differ between languages: {names}")
    lines = [
        f"// Generated by scripts/generate-knowledge.py from Sources/{target.name}/Knowledge/<lang>/*.md. Do not edit.",
        "",
        "enum KnowledgeContent {",
        "    /// Language code → document name → markdown.",
        "    static let documents: [String: [String: String]] = [",
    ]
    for lang in languages:
        lines.append(f'        "{lang}": [')
        for path in sorted((source / lang).glob("*.md")):
            text = path.read_text(encoding="utf-8")
            hashes = "#"
            while f'"{hashes}' in text or f'"""{hashes}' in text:
                hashes += "#"
            lines.append(f'            "{path.stem}": {hashes}"""')
            lines.extend(text.rstrip("\n").split("\n"))
            lines.append(f'"""{hashes},')
        lines.append("        ],")
    lines += ["    ]", "}", ""]
    output = target / "KnowledgeContent.generated.swift"
    output.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {output.relative_to(root)}")


targets = sorted(p.parent for p in (root / "Sources").glob("*/Knowledge") if p.is_dir())
if not targets:
    sys.exit("No Sources/<Target>/Knowledge folders found.")
for target in targets:
    generate(target)
