#!/usr/bin/env python3
"""Compile Sources/HeatPumpKit/Knowledge/<lang>/*.md into Swift string constants.

The markdown files stay the editable source, one folder per language (en, nb); every
language must have the same documents. Run this after editing them:
    python3 Packages/HeatPumpKit/scripts/generate-knowledge.py
A unit test fails when the generated file is out of date.
"""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
source = root / "Sources/HeatPumpKit/Knowledge"
target = root / "Sources/HeatPumpKit/Support/KnowledgeContent.generated.swift"
languages = ["en", "nb"]

names = {lang: sorted(p.stem for p in (source / lang).glob("*.md")) for lang in languages}
if len({tuple(n) for n in names.values()}) != 1:
    sys.exit(f"Knowledge documents differ between languages: {names}")

lines = [
    "// Generated by scripts/generate-knowledge.py from Sources/HeatPumpKit/Knowledge/<lang>/*.md. Do not edit.",
    "",
    "enum KnowledgeContent {",
    "    /// Language code → document name → markdown.",
    "    static let documents: [String: [String: String]] = [",
]
for lang in languages:
    lines.append(f'        "{lang}": [')
    for path in sorted((source / lang).glob("*.md")):
        text = path.read_text(encoding="utf-8")
        hashes = "#"
        while f'"{hashes}' in text or f'"""{hashes}' in text:
            hashes += "#"
        lines.append(f'            "{path.stem}": {hashes}"""')
        lines.extend(text.rstrip("\n").split("\n"))
        lines.append(f'"""{hashes},')
    lines.append("        ],")
lines += ["    ]", "}", ""]
target.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {target.relative_to(root)}")
